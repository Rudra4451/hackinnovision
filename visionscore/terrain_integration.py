"""
Terrain Intelligence & Navigation Contract Integration for ODYSSEY VisionScore 2.0.

Provides rigorous bridging between:
1. High-level visual obstacle detections & semantic segmentation.
2. Member 2's 100x100 DEM, cost_map, and risk_map.
3. Candidate navigation paths generated by Member 1 / Member 3 planners.

Core Principles:
- UNMAPPED VISUAL OBSTACLES: If an obstacle cannot be projected with certified
  extrinsic camera geometry, it is explicitly reported as an UNMAPPED VISUAL OBSTACLE
  rather than fabricating uncalibrated grid coordinates.
- NEVER TREAT VISUAL CLASSIFICATION AS PROOF OF PHYSICAL TRAVERSABILITY:
  Visual appearance cannot verify soil bearing capacity, hidden sub-surface crusts,
  or wheel sinkage.
- HARD REJECTION: Any candidate path traversing np.inf hazard cells is rejected.

Notice:
    ALL DATA PRODUCED BY THIS MODULE IS SYNTHETIC AND SIMULATED.
    IT DOES NOT REPRESENT ACTUAL IN-SITU MARS TELEMETRY OR RECONNAISSANCE MEASUREMENTS.
"""

import math
from typing import Any, Dict, List, Optional, Tuple
import numpy as np

from visionscore.obstacle_detector import ObstacleAlert


def integrate_visual_obstacle(
    terrain: Dict[str, Any],
    alert: ObstacleAlert,
    rover_position: Optional[Tuple[int, int]] = None,
    heading_deg: Optional[float] = None,
    estimated_range_m: Optional[float] = None,
) -> Dict[str, Any]:
    """
    Correlates a visual obstacle alert with the existing Terrain Intelligence map.

    If extrinsic camera geometry and rover pose are not certified, the obstacle
    is reported as an UNMAPPED VISUAL OBSTACLE per mission autonomy guidelines.

    Args:
        terrain: Dictionary returned by build_terrain_intelligence(seed=42).
        alert: Detected ObstacleAlert.
        rover_position: Optional rover grid coordinate (row, col).
        heading_deg: Optional rover azimuth heading in degrees (0 = North).
        estimated_range_m: Optional estimated distance in meters from mast camera.

    Returns:
        Structured correlation report documenting DEM agreement or unmapped status.
    """
    cost_map = terrain.get("cost_map")
    risk_map = terrain.get("risk_map")

    # If pose or range is unspecified, report as UNMAPPED VISUAL OBSTACLE
    if rover_position is None or heading_deg is None or estimated_range_m is None:
        return {
            "status": "UNMAPPED_VISUAL_OBSTACLE",
            "event_id": alert.event_id,
            "detection_category": alert.detection_category,
            "confidence": alert.confidence,
            "obstacle_area_pct": alert.obstacle_area_pct,
            "correlation_with_dem": "UNCORRELATED_UNMAPPED",
            "warning": (
                "Visual obstacle detected without certified extrinsic camera-to-grid calibration. "
                "No synthetic grid coordinates were fabricated. Physical verification recommended."
            ),
            "is_physically_verified": False,
            "requires_planner_pause": True,
        }

    # If pose and range are provided, attempt localized grid projection
    r, c = rover_position
    rad = math.radians(heading_deg)
    # Forward projection: North is -r, East is +c
    proj_r = int(round(r - estimated_range_m * math.cos(rad)))
    proj_c = int(round(c + estimated_range_m * math.sin(rad)))

    rows, cols = cost_map.shape
    if not (0 <= proj_r < rows and 0 <= proj_c < cols):
        return {
            "status": "UNMAPPED_VISUAL_OBSTACLE",
            "event_id": alert.event_id,
            "projected_coordinate": [proj_r, proj_c],
            "correlation_with_dem": "OUT_OF_BOUNDS",
            "warning": "Projected visual obstacle falls beyond the boundaries of the local terrain DEM.",
            "is_physically_verified": False,
        }

    cell_cost = float(cost_map[proj_r, proj_c])
    cell_risk = float(risk_map[proj_r, proj_c]) if risk_map is not None else 0.0

    is_dem_hazard = math.isinf(cell_cost) or cell_cost >= 1e9

    if is_dem_hazard:
        correlation = "CORRELATED_CONFIRMED_HAZARD"
        explanation = "Both live visual analysis and DEM topographical analysis agree: target cell is an impassable hazard."
    elif cell_cost > 2.0:
        correlation = "CORRELATED_CAUTION_ZONE"
        explanation = "DEM indicates elevated slope or roughness; visual sensor detects localized boulder/obstacle."
    else:
        correlation = "PERCEPTION_DISCREPANCY_WARNING"
        explanation = (
            "DEM topography marked this cell as SAFE (1.0), but live camera detection identified "
            "an unexpected localized obstacle. Dynamic cost adjustment or obstacle avoidance recommended."
        )

    return {
        "status": "PROJECTED_VISUAL_OBSTACLE",
        "event_id": alert.event_id,
        "projected_coordinate": [proj_r, proj_c],
        "dem_cost_value": "Infinity" if is_dem_hazard else round(cell_cost, 3),
        "dem_risk_value": round(cell_risk, 3),
        "correlation_with_dem": correlation,
        "explanation": explanation,
        "is_physically_verified": False,
        "requires_planner_pause": is_dem_hazard or (correlation == "PERCEPTION_DISCREPANCY_WARNING"),
    }


def evaluate_candidate_path_safety(
    path: List[Tuple[int, int]],
    cost_map: np.ndarray,
    risk_map: Optional[np.ndarray] = None,
    visual_alerts: Optional[List[ObstacleAlert]] = None,
) -> Dict[str, Any]:
    """
    Evaluates a candidate navigation path against the terrain cost map and visual alerts.

    Conforms to Member 3 navigation contract:
    - Any path crossing an impassable cell (cost == np.inf) is immediately rejected.
    - Computes a normalized 0-100 traversability score.
    - Does NOT modify pathfinding algorithms or A*.

    Args:
        path: List of (row, col) coordinates along the proposed trajectory.
        cost_map: 2D NumPy float array (SAFE=1.0, CAUTION>2.0, HAZARD=np.inf).
        risk_map: Optional 2D float array in [0.0, 1.0].
        visual_alerts: Optional list of active ObstacleAlerts.

    Returns:
        Structured evaluation dict with traversability score, rejection flags, and explanation.
    """
    if not path:
        return {
            "path_accepted": False,
            "traversability_score": 0.0,
            "rejection_reason": "Empty path sequence provided.",
            "hazard_step_count": 0,
            "caution_step_count": 0,
            "total_steps": 0,
            "explanation": "No trajectory waypoints to evaluate.",
        }

    rows, cols = cost_map.shape
    hazard_steps = 0
    caution_steps = 0
    safe_steps = 0
    total_cost = 0.0
    accumulated_risk = 0.0

    for idx, (r, c) in enumerate(path):
        if not (0 <= r < rows and 0 <= c < cols):
            return {
                "path_accepted": False,
                "traversability_score": 0.0,
                "rejection_reason": f"Waypoint index {idx} at ({r}, {c}) is out of grid bounds ({rows}, {cols}).",
                "hazard_step_count": hazard_steps + 1,
                "caution_step_count": caution_steps,
                "total_steps": len(path),
                "explanation": "Out-of-bounds trajectory violates rover boundary constraints.",
            }

        cell_c = float(cost_map[r, c])
        cell_r = float(risk_map[r, c]) if risk_map is not None else 0.0

        if math.isinf(cell_c) or cell_c >= 1e9:
            hazard_steps += 1
        elif cell_c > 2.0:
            caution_steps += 1
            total_cost += cell_c
            accumulated_risk += cell_r
        else:
            safe_steps += 1
            total_cost += 1.0
            accumulated_risk += cell_r

    # Hard rejection if ANY impassable cell is encountered
    if hazard_steps > 0:
        return {
            "path_accepted": False,
            "traversability_score": 0.0,
            "rejection_reason": f"Path intersects {hazard_steps} impassable hazard cell(s) (cost == infinity).",
            "hazard_step_count": hazard_steps,
            "caution_step_count": caution_steps,
            "safe_step_count": safe_steps,
            "total_steps": len(path),
            "explanation": "REJECTED: Proposed trajectory violates hard rover safety gate by passing through impassable obstacles.",
        }

    # Normalized traversability score in [0, 100]
    # Pure safe path has mean cost 1.0 -> 100
    # Higher costs reduce score monotonically
    avg_cost = total_cost / max(len(path), 1)
    normalized_score = max(0.0, min(100.0, 100.0 - (avg_cost - 1.0) * 5.0))

    unmapped_visual_count = 0
    if visual_alerts:
        unmapped_visual_count = sum(1 for a in visual_alerts if a.verification_status != "FALSE_POSITIVE")

    explanation = (
        f"Path evaluated successfully: {safe_steps} safe steps, {caution_steps} caution steps. "
        f"Mean step cost: {avg_cost:.2f}. "
    )
    if unmapped_visual_count > 0:
        explanation += f"Notice: {unmapped_visual_count} unmapped visual obstacle alerts active; visual sensor caution advised."

    return {
        "path_accepted": True,
        "traversability_score": round(normalized_score, 1),
        "rejection_reason": None,
        "hazard_step_count": 0,
        "caution_step_count": caution_steps,
        "safe_step_count": safe_steps,
        "total_steps": len(path),
        "mean_step_cost": round(avg_cost, 2),
        "accumulated_risk": round(accumulated_risk, 3),
        "active_visual_alerts_count": unmapped_visual_count,
        "explanation": explanation,
    }
